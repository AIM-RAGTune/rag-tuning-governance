def run_suite(
    *,
    suite: str,
    config_path: Path,
    output_dir: Path,
    run_id: str,
    resume: bool = False,
    force_new_run_id: bool = False,
) -> dict[str, Any]:
    cfg = SuiteConfig.from_path(config_path)
    if cfg.suite != suite:
        raise ValueError(f"Config suite {cfg.suite!r} does not match requested suite {suite!r}")
    if suite not in SUITE_RUNNERS:
        raise ValueError(f"Unknown RAGTune suite: {suite}")
    return SUITE_RUNNERS[suite](
        cfg,
        config_path,
        output_dir,
        run_id,
        resume=resume,
        force_new_run_id=force_new_run_id,
    )
